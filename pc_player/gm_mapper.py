def patch_for_program(program: int) -> OplPatch:
    index = max(0, min(127, program)) // 8
    return FAMILY_PATCHES[index]


def patch_for_drum(note: int) -> OplPatch:
    if note <= 36:
        return DRUM_PATCHES["kick"]
    if note <= 40:
        return DRUM_PATCHES["snare"]
    if note <= 46:
        return DRUM_PATCHES["hat"]
    if note <= 50:
        return DRUM_PATCHES["tom"]
    return DRUM_PATCHES["cymbal"]
